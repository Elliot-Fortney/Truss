const NAMESPACE = /^aws-cdk-lib\.(aws_[a-z0-9_]+)\./;

/**
 * The icon for a Node, from the jsii FQN synth reports for it (the nearest jsii class, for a class of the
 * app's own). The construct's own entry in the curated map comes first, then the icon for the service its
 * namespace names, then the generic icon. Truss never guesses from what a construct contains.
 */
export function iconFor(fqn: string): string {
  const own = CONSTRUCT_ICONS[fqn];
  if (own) return own;
  const namespace = NAMESPACE.exec(fqn)?.[1];
  return (namespace && SERVICE_ICONS[namespace]) || GENERIC_ICON;
}
